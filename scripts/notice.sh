#!/bin/sh
# Writes the NOTICE of one Sidekick binary: the third-party notices that
# ship with it and its container image. It lists every module linked into
# the Linux build, the Go standard library included, with the module's
# license and notice files. Apache License 2.0 texts are not repeated,
# since Sidekick's own LICENSE holds the same text; every other license is
# copied in full, as those licenses require.
# Usage: scripts/notice.sh [package] > NOTICE
# The package is ./cmd/sidekick (the default) or ./cmd/sidekick-validate.
set -eu

package="${1:-./cmd/sidekick}"

# The image is built for Linux, and the modules linked in can differ by
# platform.
GOOS=linux
GOARCH=amd64
CGO_ENABLED=0
export GOOS GOARCH CGO_ENABLED

. "$(dirname "$0")/notice-lib.sh"

case "$package" in
./cmd/sidekick)
	cat <<'EOF'
Sidekick
Copyright 2026 The Sidekick Authors

This product is licensed under the Apache License, Version 2.0 (see
LICENSE). Its binary and container image include the third-party software
listed below, each under its own license. Where a component is under the
Apache License, Version 2.0, the license text is the one in LICENSE, and
only the component's own NOTICE file, if it has one, is copied here.

This file is generated by scripts/notice.sh; run `make notice` after
changing dependencies.
EOF
	;;
./cmd/sidekick-validate)
	cat <<'EOF'
Sidekick validator (sidekick-validate)
Copyright 2026 The Sidekick Authors

This product is licensed under the Apache License, Version 2.0 (see
LICENSE). The sidekick-validate binary includes the third-party Go modules
listed below, and the validator image also ships the third-party tools
listed after them, each under its own license. Where a component is under
the Apache License, Version 2.0, the license text is the one in LICENSE,
and only the component's own NOTICE file, if it has one, is copied here.

The Go modules part is generated by scripts/notice.sh; run `make notice`
after changing dependencies. The tools part is added when the validator
image is built, by scripts/validator-notice.sh.
EOF
	;;
*)
	echo "notice.sh: unknown package $package" >&2
	exit 1
	;;
esac

go_license

main=$(go list -m)

for module in $(go list -deps -f '{{if .Module}}{{.Module.Path}}{{end}}' "$package" | LC_ALL=C sort -u); do
	if [ "$module" = "$main" ]; then
		continue
	fi

	version=$(go list -m -f '{{.Version}}' "$module")
	dir=$(go mod download -json "$module@$version" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')

	section "$module $version" "$dir"
done

# The npm packages bundled into the web UI, as the UI build listed them.
if [ "$package" = ./cmd/sidekick ]; then
	node "$(dirname "$0")/../web/build/notice.mjs"
fi
