package grafana

import (
	"encoding/json"
	"fmt"
	"math"
	"slices"

	"github.com/prometheus/common/model"

	"github.com/nourtalaat/sidekick/internal/action"
)

// What Grafana checks when it stores a rule, as its source shows (tag
// v13.2.5 of github.com/grafana/grafana; paths are under
// pkg/services/ngalert/):
//
//   - models/alert_rule.go, ValidateAlertRule and validateAlertRuleFields:
//     the title is not empty, noDataState and execErrState are one of their
//     values, for and keep_firing_for are not negative, and a label may not
//     be one of the labels Grafana reserves.
//   - store/alert_rule.go, validateAlertRule: the title has at most 190
//     bytes.
//   - models/alert_rule.go, SetDashboardAndPanelFromAnnotations: the
//     __dashboardUid__ and __panelId__ annotations come as a pair.
//   - models/alert_query.go, PreSave: a query that is not an expression has
//     a relativeTimeRange whose from is greater than its to, and a
//     model.queryType must be text.
//   - api/compat/compat.go and api/tooling/definitions/cortex-ruler.go: a
//     query has the keys refId, queryType, relativeTimeRange (from and to,
//     whole seconds), datasourceUid and model. Grafana drops any other key
//     without a word.
//
// Grafana has no call that checks a rule without storing it, so these checks
// are repeated here, when the model proposes. A change that Grafana would
// refuse then comes back to the model as a message it can act on, and a
// change that Grafana would drop silently never reaches an approver.

// Values Grafana checks for.
const (
	// maxTitleBytes is the longest rule title Grafana stores.
	maxTitleBytes = 190
	// expressionUID and oldExpressionUID are the data source UIDs of a
	// server side expression, whose time range is not checked.
	expressionUID    = "__expr__"
	oldExpressionUID = "-100"
	// dashboardAnnotation and panelAnnotation link a rule to a panel.
	dashboardAnnotation = "__dashboardUid__"
	panelAnnotation     = "__panelId__"
	// maxWholeSeconds is the largest time range accepted, to keep the check
	// of whole numbers exact.
	maxWholeSeconds = 1 << 50
)

var (
	noDataStates   = []string{"Alerting", "NoData", "OK", "KeepLast"}
	execErrStates  = []string{"Alerting", "Error", "OK", "KeepLast"}
	reservedLabels = []string{"__grafana_autogenerated__", "__grafana_receiver__", "__grafana_route_settings_hash__"}
	queryKeys      = []string{"refId", "queryType", "relativeTimeRange", "datasourceUid", "model"}
)

// checkChange refuses a change that Grafana would refuse or drop. It looks
// at the fields the change touches: the result of the change must be a rule
// Grafana stores as written.
func checkChange(before, after json.RawMessage, deltas []action.Delta) error {
	oldRule, ok := objectOf(before)
	if !ok {
		return refuse("the rule is not an object")
	}

	newRule, ok := objectOf(after)
	if !ok {
		return refuse("the rule after the change is not an object")
	}

	for _, root := range touchedRoots(deltas) {
		_, shown := oldRule[root]
		if !shown && root != "labels" && root != "annotations" {
			return refuse("the rule has no field %q, so this Grafana would drop a value written there", root)
		}

		if err := checkRoot(root, oldRule, newRule); err != nil {
			return fmt.Errorf("check %s: %w", root, err)
		}
	}

	return nil
}

// touchedRoots returns the first key of each path of the deltas, once each.
func touchedRoots(deltas []action.Delta) []string {
	var roots []string

	for _, d := range deltas {
		if len(d.Path) > 0 && !slices.Contains(roots, d.Path[0]) {
			roots = append(roots, d.Path[0])
		}
	}

	return roots
}

// checkRoot checks the field root of the rule after the change.
func checkRoot(root string, oldRule, newRule map[string]json.RawMessage) error {
	switch root {
	case "title":
		return checkTitle(newRule["title"])
	case "condition":
		return checkCondition(newRule)
	case "data":
		if err := checkData(newRule["data"]); err != nil {
			return fmt.Errorf("check the queries: %w", err)
		}

		return checkCondition(newRule)
	case "noDataState":
		return checkOneOf(newRule[root], noDataStates)
	case "execErrState":
		return checkOneOf(newRule[root], execErrStates)
	case "for", "keep_firing_for":
		return checkDuration(newRule[root])
	case "isPaused":
		return checkBool(newRule[root])
	case "labels":
		return checkLabels(oldRule[root], newRule[root])
	case "annotations":
		return checkAnnotations(oldRule[root], newRule[root])
	default:
		return refuse("the field %q cannot be changed by this action", root)
	}
}

// checkTitle checks the title of a rule.
func checkTitle(raw json.RawMessage) error {
	title, ok := textOf(raw)

	switch {
	case !ok:
		return refuse("the title must be text")
	case title == "":
		return refuse("the title must not be empty")
	case len(title) > maxTitleBytes:
		return refuse("the title has %d bytes; Grafana keeps at most %d", len(title), maxTitleBytes)
	default:
		return nil
	}
}

// checkCondition checks that the condition of the rule is the refId of one of
// its queries, which Grafana evaluates it by.
func checkCondition(rule map[string]json.RawMessage) error {
	condition, ok := textOf(rule["condition"])
	if !ok || condition == "" {
		return refuse("the condition must be the refId of one of the queries in data")
	}

	queries, _ := listOf(rule["data"])
	for _, raw := range queries {
		query, _ := objectOf(raw)
		if refID, _ := textOf(query["refId"]); refID == condition {
			return nil
		}
	}

	return refuse("the condition %q is not the refId of any query in data", condition)
}

// checkData checks the queries of a rule.
func checkData(raw json.RawMessage) error {
	queries, ok := listOf(raw)
	if !ok || len(queries) == 0 {
		return refuse("data must be a list with at least one query")
	}

	for i, item := range queries {
		if err := checkQuery(item); err != nil {
			return fmt.Errorf("query %d: %w", i, err)
		}
	}

	return nil
}

// checkQuery checks one query of a rule.
func checkQuery(raw json.RawMessage) error {
	query, ok := objectOf(raw)
	if !ok {
		return refuse("a query must be an object")
	}

	for key := range query {
		if !slices.Contains(queryKeys, key) {
			return refuse("a query has the keys %v; Grafana drops %q", queryKeys, key)
		}
	}

	for _, key := range []string{"refId", "datasourceUid"} {
		if text, ok := textOf(query[key]); !ok || text == "" {
			return refuse("%s must be text and not empty", key)
		}
	}

	body, ok := objectOf(query["model"])
	if !ok {
		return refuse("model must be an object")
	}

	if err := checkModel(query, body); err != nil {
		return fmt.Errorf("check the model: %w", err)
	}

	return checkTimeRange(query)
}

// checkModel refuses a value in the model of a query that Grafana replaces
// when it stores the query, so a change never reads back as another value:
// maxDataPoints and intervalMs that are 0 or not a number, a refId that is
// not the refId of the query, and a queryType that is not the one of the
// query.
func checkModel(query, body map[string]json.RawMessage) error {
	for _, key := range []string{"maxDataPoints", "intervalMs"} {
		value, present := body[key]
		if !present {
			continue
		}

		var n float64
		if json.Unmarshal(value, &n) != nil || n == 0 {
			return refuse("model.%s must be a number other than 0; Grafana replaces anything else with a default", key)
		}
	}

	refID, _ := textOf(query["refId"])

	if modelID, present := body["refId"]; present {
		if text, ok := textOf(modelID); !ok || text != refID {
			return refuse("model.refId must be the refId of the query, %q; Grafana sets it", refID)
		}
	}

	if raw, present := body["queryType"]; present {
		kind, ok := textOf(raw)
		if !ok {
			return refuse("model.queryType must be text")
		}

		if own, _ := textOf(query["queryType"]); own != "" && kind != "" && own != kind {
			return refuse("queryType and model.queryType must be the same; Grafana takes the one in the model")
		}
	}

	return nil
}

// checkTimeRange checks the relativeTimeRange of a query: whole seconds, and
// for a query that is not an expression, from greater than to.
func checkTimeRange(query map[string]json.RawMessage) error {
	var from, to float64

	if raw, present := query["relativeTimeRange"]; present {
		span, ok := objectOf(raw)
		if !ok {
			return refuse("relativeTimeRange must be an object with from and to")
		}

		for key := range span {
			if key != "from" && key != "to" {
				return refuse("relativeTimeRange has from and to; Grafana drops %q", key)
			}
		}

		var err error

		if from, err = wholeSeconds(span["from"]); err != nil {
			return fmt.Errorf("relativeTimeRange.from: %w", err)
		}

		if to, err = wholeSeconds(span["to"]); err != nil {
			return fmt.Errorf("relativeTimeRange.to: %w", err)
		}
	}

	uid, _ := textOf(query["datasourceUid"])
	if uid != expressionUID && uid != oldExpressionUID && from <= to {
		return refuse("relativeTimeRange.from must be greater than relativeTimeRange.to for a query that is not an expression")
	}

	return nil
}

// wholeSeconds reads a number of seconds. A missing value is 0.
func wholeSeconds(raw json.RawMessage) (float64, error) {
	if raw == nil {
		return 0, nil
	}

	var n float64
	if json.Unmarshal(raw, &n) != nil || n != math.Trunc(n) || math.Abs(n) > maxWholeSeconds {
		return 0, refuse("must be a whole number of seconds")
	}

	return n, nil
}

// checkOneOf checks that raw is text that is one of values.
func checkOneOf(raw json.RawMessage, values []string) error {
	text, ok := textOf(raw)
	if !ok || !slices.Contains(values, text) {
		return refuse("the value must be one of %v", values)
	}

	return nil
}

// checkDuration checks that raw is a duration as text, such as 5m, that is
// not negative (the parser takes none).
func checkDuration(raw json.RawMessage) error {
	text, ok := textOf(raw)
	if !ok {
		return refuse("a duration must be text, such as 5m")
	}

	if _, err := model.ParseDuration(text); err != nil {
		return refuse("%q is not a duration such as 5m or 1h30m", text)
	}

	return nil
}

// checkBool checks that raw is true or false.
func checkBool(raw json.RawMessage) error {
	var value any
	if json.Unmarshal(raw, &value) != nil {
		return refuse("the value must be true or false")
	}

	if _, ok := value.(bool); !ok {
		return refuse("the value must be true or false")
	}

	return nil
}

// checkLabels checks the labels after a change: text values, and none of the
// labels Grafana reserves unless the rule had it before.
func checkLabels(oldRaw, newRaw json.RawMessage) error {
	labels, err := textMap(newRaw)
	if err != nil {
		return fmt.Errorf("read the labels: %w", err)
	}

	old, _ := textMap(oldRaw)

	for _, name := range reservedLabels {
		value, has := labels[name]

		oldValue, hadOld := old[name]
		if has && (!hadOld || oldValue != value) {
			return refuse("the label %q is reserved by Grafana", name)
		}
	}

	return nil
}

// checkAnnotations checks the annotations after a change: text values, and
// the dashboard and panel annotations, which tie the rule to a panel, as
// they were.
func checkAnnotations(oldRaw, newRaw json.RawMessage) error {
	annotations, err := textMap(newRaw)
	if err != nil {
		return fmt.Errorf("read the annotations: %w", err)
	}

	old, _ := textMap(oldRaw)

	for _, name := range []string{dashboardAnnotation, panelAnnotation} {
		oldValue, hadOld := old[name]

		newValue, hasNew := annotations[name]
		if hadOld != hasNew || oldValue != newValue {
			return refuse("the annotation %q ties the rule to a dashboard panel and cannot be changed", name)
		}
	}

	return nil
}

// textMap reads an object whose values are all text. Nothing is an empty map.
func textMap(raw json.RawMessage) (map[string]string, error) {
	if raw == nil {
		return map[string]string{}, nil
	}

	entries, ok := objectOf(raw)
	if !ok {
		return nil, refuse("must be an object of text values; set an entry to null to remove it")
	}

	out := make(map[string]string, len(entries))

	for name, value := range entries {
		text, ok := textOf(value)
		if !ok {
			return nil, refuse("the value of %q must be text", name)
		}

		out[name] = text
	}

	return out, nil
}

// dropNullEntries removes the labels and annotations the change set to null,
// which is how the model removes one: Grafana would store a null label as an
// empty text, so a null never goes to Grafana. A map left empty is dropped
// when the rule had none before, as Grafana leaves an empty map out of its
// answer.
func dropNullEntries(before, after json.RawMessage) (json.RawMessage, error) {
	oldRule, _ := objectOf(before)

	rule, ok := objectOf(after)
	if !ok {
		return nil, refuse("the rule after the change is not an object")
	}

	for _, key := range []string{"labels", "annotations"} {
		raw, present := rule[key]
		if !present {
			continue
		}

		entries, ok := objectOf(raw)
		if !ok && !isNull(raw) {
			continue
		}

		for name, value := range entries {
			if isNull(value) {
				delete(entries, name)
			}
		}

		if _, had := oldRule[key]; len(entries) == 0 && !had {
			delete(rule, key)

			continue
		}

		if entries == nil {
			entries = map[string]json.RawMessage{}
		}

		out, err := json.Marshal(entries)
		if err != nil {
			return nil, fmt.Errorf("encode the %s: %w", key, err)
		}

		rule[key] = out
	}

	out, err := json.Marshal(rule)
	if err != nil {
		return nil, fmt.Errorf("encode the rule: %w", err)
	}

	return out, nil
}

// refuse makes the error of a change that is not allowed, with a message the
// model can act on. It wraps action.ErrLimit.
func refuse(format string, args ...any) error {
	return fmt.Errorf("%s: %w", fmt.Sprintf(format, args...), action.ErrLimit)
}
